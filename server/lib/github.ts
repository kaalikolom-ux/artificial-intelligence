export interface GitHubUser {
  id: number;
  login: string;
  name: string | null;
  email: string | null;
  avatar_url: string;
}

export async function exchangeGitHubCode(
  clientId: string,
  clientSecret: string,
  code: string
): Promise<string> {
  const response = await fetch("https://github.com/login/oauth/access_token", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Accept: "application/json",
    },
    body: JSON.stringify({
      client_id: clientId,
      client_secret: clientSecret,
      code,
    }),
  });

  const data = (await response.json()) as { access_token?: string; error?: string };
  if (!data.access_token) {
    throw new Error(data.error || "Failed to obtain GitHub access token");
  }

  return data.access_token;
}

export async function getGitHubUserProfile(token: string): Promise<GitHubUser> {
  const response = await fetch("https://api.github.com/user", {
    headers: {
      Authorization: `Bearer ${token}`,
      "User-Agent": "Lovable-Clone-Cloudflare",
      Accept: "application/vnd.github.v3+json",
    },
  });

  if (!response.ok) {
    throw new Error("Failed to fetch GitHub profile");
  }

  return (await response.json()) as GitHubUser;
}

export async function pushFilesToGitHub(
  token: string,
  repoName: string,
  files: { path: string; content: string }[],
  isPrivate = false
): Promise<{ repoUrl: string }> {
  const headers = {
    Authorization: `Bearer ${token}`,
    "User-Agent": "Lovable-Clone-Cloudflare",
    Accept: "application/vnd.github.v3+json",
  };

  // 1. Check or create repo
  let repoData: any;
  const checkRepo = await fetch(`https://api.github.com/user/repos`, {
    method: "POST",
    headers,
    body: JSON.stringify({
      name: repoName,
      description: "Generated by Lovable AI App Studio",
      private: isPrivate,
      auto_init: true,
    }),
  });

  if (checkRepo.status === 422) {
    // Repo might already exist, fetch user info first
    const user = await getGitHubUserProfile(token);
    const existingRepo = await fetch(`https://api.github.com/repos/${user.login}/${repoName}`, {
      headers,
    });
    repoData = await existingRepo.json();
  } else if (!checkRepo.ok) {
    const err = await checkRepo.text();
    throw new Error(`Failed to create repository: ${err}`);
  } else {
    repoData = await checkRepo.json();
  }

  const owner = repoData.owner.login;
  const repo = repoData.name;

  // 2. Commit files one by one or via tree
  // For simplicity and robustness across small/medium projects, we update or create contents via GitHub REST
  for (const file of files) {
    // check if file already exists to get its SHA
    let sha: string | undefined = undefined;
    const fileRes = await fetch(`https://api.github.com/repos/${owner}/${repo}/contents/${file.path}`, {
      headers,
    });
    if (fileRes.ok) {
      const existing = (await fileRes.json()) as { sha: string };
      sha = existing.sha;
    }

    // Base64 encode file content
    const base64Content = btoa(unescape(encodeURIComponent(file.content)));

    await fetch(`https://api.github.com/repos/${owner}/${repo}/contents/${file.path}`, {
      method: "PUT",
      headers,
      body: JSON.stringify({
        message: `Update ${file.path} from Lovable AI`,
        content: base64Content,
        sha,
      }),
    });
  }

  return { repoUrl: repoData.html_url };
}
